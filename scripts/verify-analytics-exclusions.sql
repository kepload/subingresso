-- Run against production only inside this rollback transaction. No messages or mail.
BEGIN;
SET LOCAL lock_timeout='5s';
SET LOCAL statement_timeout='60s';
DO $test$
DECLARE internal uuid; administrator uuid; customer uuid; listing uuid; sid uuid:=gen_random_uuid();
 before_views integer; before_saved integer; before_daily bigint; before_saved_rows bigint;
 before_events bigint; before_identifiers bigint; result jsonb; f text;
BEGIN
 IF (SELECT count(*) FROM data_quality.analytics_excluded_accounts)<>2 THEN RAISE EXCEPTION 'Expected two configured owner accounts'; END IF;
 SELECT p.id INTO administrator FROM public.profiles p JOIN data_quality.analytics_excluded_accounts e ON e.user_id=p.id WHERE p.is_admin;
 SELECT p.id INTO internal FROM public.profiles p JOIN data_quality.analytics_excluded_accounts e ON e.user_id=p.id WHERE NOT p.is_admin;
 SELECT id INTO customer FROM public.profiles WHERE NOT data_quality.analytics_account_excluded(id) ORDER BY created_at LIMIT 1;
 SELECT id INTO listing FROM public.annunci WHERE status='active' AND expires_at>now() AND NOT data_quality.analytics_account_excluded(user_id) AND user_id<>customer LIMIT 1;
 IF internal IS NULL OR administrator IS NULL OR customer IS NULL OR listing IS NULL THEN RAISE EXCEPTION 'Missing test identities/listing'; END IF;
 IF has_table_privilege('authenticated','data_quality.analytics_excluded_accounts','SELECT') OR has_table_privilege('anon','data_quality.analytics_excluded_identifiers','INSERT') OR has_function_privilege('authenticated','public.analytics_excluded_account_ids()','EXECUTE') THEN RAISE EXCEPTION 'Private registry exposed'; END IF;
 IF EXISTS(SELECT 1 FROM data_quality.analytics_payments WHERE user_id IN(SELECT user_id FROM data_quality.analytics_excluded_accounts)) THEN RAISE EXCEPTION 'Owner payment in business stats'; END IF;
 IF EXISTS(SELECT 1 FROM data_quality.analytics_profiles WHERE id IN(SELECT user_id FROM data_quality.analytics_excluded_accounts)) THEN RAISE EXCEPTION 'Owner profile in business stats'; END IF;
 IF EXISTS(SELECT 1 FROM data_quality.analytics_daily_save_corrections c JOIN public.listing_stats_daily s ON s.annuncio_id=c.listing_id AND s.day=c.day WHERE s.saves<>greatest(c.old_saves-c.removed_saves,0)) THEN RAISE EXCEPTION 'Historical save correction applied more than once'; END IF;
 IF EXISTS(SELECT 1 FROM public.annunci a WHERE a.saved_count<>(SELECT count(*) FROM public.saved_listings s WHERE s.annuncio_id=a.id AND NOT data_quality.analytics_account_excluded(s.user_id))) THEN RAISE EXCEPTION 'Public favorite count differs from retained customer saves'; END IF;
 SELECT visualizzazioni,saved_count INTO before_views,before_saved FROM public.annunci WHERE id=listing;
 SELECT coalesce(sum(views+call_clicks+whatsapp_clicks+chat_clicks+saves),0) INTO before_daily FROM public.listing_stats_daily WHERE annuncio_id=listing;
 SELECT count(*) INTO before_events FROM public.page_views;
 SELECT count(*) INTO before_saved_rows FROM public.saved_listings;
 FOREACH internal IN ARRAY ARRAY[internal,administrator] LOOP
  PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',internal,'role','authenticated')::text,true);
  result:=public.analytics_tracking_context('qa-owner-visitor-'||sid::text,sid::text,'qa-owner-auth-'||sid::text);
  IF result->>'excluded'<>'true' OR result->>'user_id'<>internal::text THEN RAISE EXCEPTION 'Owner not recognized'; END IF;
  PERFORM public.track_listing_view(listing,'detail');
  PERFORM public.track_listing_event(listing,'whatsapp',1);
  INSERT INTO public.page_views(path,visitor_id,session_id) VALUES('/','qa-owner-'||sid::text,'qa-owner-'||sid::text);
  INSERT INTO public.blog_conversions(post_slug,kind,visitor_id,session_id) VALUES('qa-owner','cta_annunci_click','qa-owner-'||sid::text,'qa-owner-'||sid::text);
  DELETE FROM public.saved_listings WHERE user_id=internal AND annuncio_id=listing;
  INSERT INTO public.saved_listings(user_id,annuncio_id) VALUES(internal,listing);
  IF NOT EXISTS(SELECT 1 FROM public.saved_listings WHERE user_id=internal AND annuncio_id=listing) THEN RAISE EXCEPTION 'Owner cannot save'; END IF;
  IF (SELECT saved_count FROM public.annunci WHERE id=listing)<>before_saved THEN RAISE EXCEPTION 'Owner save changed public counter'; END IF;
  DELETE FROM public.saved_listings WHERE user_id=internal AND annuncio_id=listing;
  IF (SELECT saved_count FROM public.annunci WHERE id=listing)<>before_saved THEN RAISE EXCEPTION 'Owner unsave changed counter'; END IF;
 END LOOP;
 IF (SELECT visualizzazioni FROM public.annunci WHERE id=listing)<>before_views THEN RAISE EXCEPTION 'Owner listing view counted'; END IF;
 IF (SELECT coalesce(sum(views+call_clicks+whatsapp_clicks+chat_clicks+saves),0) FROM public.listing_stats_daily WHERE annuncio_id=listing)<>before_daily THEN RAISE EXCEPTION 'Owner daily activity counted'; END IF;
 IF (SELECT count(*) FROM public.page_views)<>before_events THEN RAISE EXCEPTION 'Owner page view counted'; END IF;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',administrator,'role','authenticated')::text,true);
 PERFORM public.admin_control_room();
 PERFORM public.admin_business_stats();
 PERFORM public.admin_total_listing_value();
 PERFORM public.admin_listings_per_regione();
 PERFORM public.admin_funnel_stats();
 PERFORM public.admin_page_views_stats();
 PERFORM public.admin_revenue_stats();
 PERFORM public.admin_acquisition_stats(30);
 PERFORM public.admin_blog_stats(30);
 PERFORM public.admin_personal_ads(30);
 PERFORM public.admin_personal_ad_events();
 PERFORM public.admin_site_analytics();
 PERFORM public.admin_top_location_searches();
 PERFORM public.admin_blog_listing_ads();
 PERFORM public.admin_vetrina_conversion_stats();
 PERFORM public.admin_signup_funnel_by_source();
 PERFORM public.admin_bando_alerts_stats();
 PERFORM public.dashboard_seller_analytics();
 PERFORM public.dashboard_vetrina_stats();
 PERFORM public.get_my_profile();
 PERFORM public.get_listing_contact(listing);
 -- A different customer keeps ordinary tracking and cannot mark other people excluded.
 SELECT count(*) INTO before_identifiers FROM data_quality.analytics_excluded_identifiers;
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',customer,'role','authenticated')::text,true);
 result:=public.analytics_tracking_context('qa-customer-'||sid::text,'qa-customer-'||sid::text,NULL);
 IF result->>'excluded'<>'false' OR (SELECT count(*) FROM data_quality.analytics_excluded_identifiers)<>before_identifiers THEN RAISE EXCEPTION 'Customer exclusion isolation'; END IF;
 PERFORM public.track_listing_view(listing,'detail');
 IF (SELECT visualizzazioni FROM public.annunci WHERE id=listing)<>before_views+1 THEN RAISE EXCEPTION 'Customer view lost'; END IF;
 DELETE FROM public.saved_listings WHERE user_id=customer AND annuncio_id=listing;
 SELECT saved_count INTO before_saved FROM public.annunci WHERE id=listing;
 INSERT INTO public.saved_listings(user_id,annuncio_id) VALUES(customer,listing);
 IF (SELECT saved_count FROM public.annunci WHERE id=listing)<>before_saved+1 THEN RAISE EXCEPTION 'Customer save lost'; END IF;
 -- Known owner identifiers are still ignored without a login; unknown visitors work.
 PERFORM set_config('request.jwt.claims','{}',true);
 INSERT INTO public.page_views(path,visitor_id,session_id) VALUES('/','qa-owner-visitor-'||sid::text,sid::text);
 IF (SELECT count(*) FROM public.page_views)<>before_events THEN RAISE EXCEPTION 'Known anonymous owner counted'; END IF;
 INSERT INTO public.page_views(path,visitor_id,session_id) VALUES('/','qa-customer-'||sid::text,'qa-customer-'||sid::text);
 IF (SELECT count(*) FROM public.page_views)<>before_events+1 THEN RAISE EXCEPTION 'Ordinary visitor lost'; END IF;
END $test$;
SELECT jsonb_build_object('passed',true,'rollback',true,'checks','two accounts; business reports; owner saves/unsaves/contacts; ordinary tracking; anonymous marker; permissions; preserved admin access') AS result;
ROLLBACK;
